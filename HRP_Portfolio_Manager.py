def analyze_defensive_metrics(strategy_rets, benchmark_rets):
    print("\n====== DEFENSIVE METRICS (The 'Real' Story) ======")

    # 1. Capture Ratios
    # Upside: How much of the bull market did we catch?
    up_market = benchmark_rets[benchmark_rets > 0]
    strat_up = strategy_rets[benchmark_rets > 0]
    upside_capture = strat_up.mean() / up_market.mean()

    # Downside: How much of the crash did we feel?
    down_market = benchmark_rets[benchmark_rets < 0]
    strat_down = strategy_rets[benchmark_rets < 0]
    downside_capture = strat_down.mean() / down_market.mean()

    # Helper for formatting
    def scalar(x):
        if hasattr(x, "item"): return x.item()
        return x

    print(f"Upside Capture:   {scalar(upside_capture)*100:.2f}% ")
    print(f"Downside Capture: {scalar(downside_capture)*100:.2f}%")

    # 2. Win Rate (Positive Periods)
    positive_months = (strategy_rets > 0).sum() / len(strategy_rets)
    print(f"Win Rate (Days):  {scalar(positive_months)*100:.2f}%")

    print("--------------------------------------------------")
    dc = scalar(downside_capture)
    if dc < 0.6:
        print("✅ SUCCESS: Your model is a 'Crash Shield'.\n   It ignores a huge portion of market losses.")
    else:
        print("⚠️ NOTE: Downside protection is average.")

