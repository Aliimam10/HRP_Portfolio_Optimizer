# Training Window: 504 trading days (approx 2 years) to learn correlations
TRAINING_WINDOW = 504
# Rebalance Frequency: 63 trading days (Quarterly)
REBALANCE_FREQ = 63

def enforce_min_weights(weights_dict, min_w=0.08):
    """
    Forces the 8% floor during backtesting so the simulation
    matches the real strategy.
    """
    weights = pd.Series(weights_dict)

    # Force the floor
    weights[weights < min_w] = min_w

    # Renormalize
    fixed_total = weights[weights == min_w].sum()
    flexible_indices = weights[weights > min_w].index

    if len(flexible_indices) > 0:
        remaining_budget = 1.0 - fixed_total
        current_flex_total = weights[flexible_indices].sum()
        weights[flexible_indices] *= (remaining_budget / current_flex_total)

    return weights.to_dict()

# ==========================================
# 2. THE HRP OPTIMIZER (Helper)
# ==========================================
def get_hrp_weights(historical_data):
    """
    Calculates optimal weights based ONLY on the past data provided.
    """
    try:
        hrp = HRPOpt(returns=historical_data)
        weights = hrp.optimize()
        return enforce_min_weights(weights, min_w=0.08)

    except Exception as e:
        # Fallback to Equal Weights
        n = historical_data.shape[1]
        return {col: 1.0/n for col in historical_data.columns}

# 3. THE WALK-FORWARD BACKTEST LOOP

def run_walk_forward(returns_data):
    print(f"--- Starting Walk-Forward Backtest (Total Days: {len(returns_data)}) ---")

    # We start trading ONLY after the first training window
    start_index = TRAINING_WINDOW
    rebalance_dates = range(start_index, len(returns_data), REBALANCE_FREQ)

    portfolio_history = []

    for i in rebalance_dates:
        # A. Define the PAST (Training Window)
        # Strictly slice [Current - 2 Years] to [Current Day]
        train_window = returns_data.iloc[i-TRAINING_WINDOW : i]

        # B. Define the FUTURE (Test Window)
        # Slice [Current Day] to [Next Rebalance]
        if i + REBALANCE_FREQ >= len(returns_data):
            test_window = returns_data.iloc[i:]
        else:
            test_window = returns_data.iloc[i : i+REBALANCE_FREQ]

        # C. The Decision
        weights = get_hrp_weights(train_window)
        weights_series = pd.Series(weights)

        # D. The Result
        # Multiply future returns by the weights we chose
        period_returns = (test_window * weights_series).sum(axis=1)
        portfolio_history.append(period_returns)

    # Stitch results into one timeline
    full_curve = pd.concat(portfolio_history)
    print("Backtest Complete.")
    return full_curve

