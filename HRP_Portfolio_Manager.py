# Enforcing a minimum 8% weightage contraint
def enforce_min_weights(weights_dict, min_w=0.08):
    """
    Manually forces every asset to have at least 'min_w' weight (e.g., 8%).
    Renormalizes the remaining assets so the total equals 100%.
    """
    weights = pd.Series(weights_dict)

    # 1. Force the floor
    weights[weights < min_w] = min_w

    # 2. Re-normalize the 'Big' weights so the sum is exactly 1.0
    # Calculate how much space is taken by the fixed minimums
    fixed_total = weights[weights == min_w].sum()

    # Identify the flexible assets (those above the minimum)
    flexible_indices = weights[weights > min_w].index

    if len(flexible_indices) > 0:
        # How much room is left for the big assets?
        remaining_budget = 1.0 - fixed_total

        # Scale them down proportionally to fit the budget
        current_flex_total = weights[flexible_indices].sum()
        weights[flexible_indices] *= (remaining_budget / current_flex_total)

    return weights.to_dict()

# 1. THE HRP OPTIMIZATION ENGINE

def run_hrp_model(returns_data):
    print("--- Training HRP Model ---")

    # Initialize. it automatically trains the data and make the covariances
    hrp = HRPOpt(returns=returns_data)

    # Optimize (Raw unconstrained weights)
    raw_weights = hrp.optimize()

    # --- THE CHANGE IS HERE ---
    # Instead of just cleaning, we APPLY THE 8% FLOOR
    print(f"Applying Minimum Weight Constraint: {8}%")
    final_weights = enforce_min_weights(raw_weights, min_w=0.08)

    print("Optimization Complete.")
    print("---------------------------------")
    return hrp, final_weights

