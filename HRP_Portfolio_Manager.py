# Outputting the results
def generate_standard_report(strategy_rets, benchmark_ticker="SPY"):
    print("\n--- Fetching Benchmark (S&P 500) ---")

    start = strategy_rets.index[0]
    end = strategy_rets.index[-1]

    # robust download
    bench_data = yf.download(benchmark_ticker, start=start, end=end, progress=False)

    # Handle yfinance Data Structure (Fixing the TypeError)
    if isinstance(bench_data, pd.DataFrame):
        # If MultiIndex or extra columns, try to get 'Close' or 'Adj Close'
        if 'Adj Close' in bench_data.columns:
            bench_data = bench_data['Adj Close']
        elif 'Close' in bench_data.columns:
            bench_data = bench_data['Close']

        # If it's still a DataFrame (e.g. SPY as column name), squeeze it
        if isinstance(bench_data, pd.DataFrame):
            bench_data = bench_data.iloc[:, 0]

    bench_rets = bench_data.pct_change().dropna()

    # Align dates
    common_idx = strategy_rets.index.intersection(bench_rets.index)
    strat = strategy_rets.loc[common_idx]
    bench = bench_rets.loc[common_idx]

    # Metrics
    cum_strat = (1 + strat).cumprod()
    cum_bench = (1 + bench).cumprod()

    sharpe_strat = (strat.mean() / strat.std()) * np.sqrt(252)
    sharpe_bench = (bench.mean() / bench.std()) * np.sqrt(252)

    # Max Drawdown Helper
    def get_dd(series):
        roll_max = series.cummax()
        dd = (series - roll_max) / roll_max
        return dd.min()

    mdd_strat = get_dd(cum_strat)
    mdd_bench = get_dd(cum_bench)

    # Helper to extract scalar values safely (The Fix)
    def scalar(x):
        if hasattr(x, "item"): return x.item()
        return x

    print("\n====== STANDARD PERFORMANCE REPORT ======")
    print(f"{'Metric':<20} | {'HRP Strategy':<15} | {'S&P 500 (SPY)':<15}")
    print("-" * 55)
    print(f"{'Total Return':<20} | {(scalar(cum_strat.iloc[-1])-1)*100:.2f}% | {(scalar(cum_bench.iloc[-1])-1)*100:.2f}%")
    print(f"{'Max Drawdown':<20} | {scalar(mdd_strat)*100:.2f}% | {scalar(mdd_bench)*100:.2f}%")
    print(f"{'Sharpe Ratio':<20} | {scalar(sharpe_strat):.2f}   | {scalar(sharpe_bench):.2f}")

    # Plot
    plt.figure(figsize=(12, 6))
    plt.plot(cum_strat, label="HRP (Barbell Portfolio)", color='#2ecc71', linewidth=2)
    plt.plot(cum_bench, label="S&P 500", color='gray', linestyle='--', alpha=0.6)


    plt.title("HRP vs S&P 500: Wealth Preservation Test", fontsize=14)
    plt.ylabel("Growth of $1 Investment")
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.show()

    return strat, bench

