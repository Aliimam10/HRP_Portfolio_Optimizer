# 3. PREPROCESSING (Returns & Outliers)

def process_returns(price_data):
    print("\n--- 2. Calculating Returns & Cleaning Outliers ---")

    # Calculate Daily Percentage Change
    returns = price_data.pct_change().dropna()

    # WINSORIZATION (The "Safety Valve")
    # We clip the top 1% and bottom 1% of extreme moves.
    # This prevents a single "flash crash" glitch from breaking the model.
    lower_limit = returns.quantile(0.01)
    upper_limit = returns.quantile(0.99)

    # Apply the clip
    clean_returns = returns.clip(lower=lower_limit, upper=upper_limit, axis=1)

    print("Outliers (1% / 99%) have been clipped.")
    return clean_returns

